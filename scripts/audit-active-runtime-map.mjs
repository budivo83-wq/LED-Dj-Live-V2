import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";

const root = process.cwd();
const outDir = path.join(root, "docs", "runtime");
fs.mkdirSync(outDir, { recursive: true });

function readJsonFromAuditImports() {
  const raw = execFileSync(process.execPath, ["scripts/audit-imports.mjs"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024
  });
  return JSON.parse(raw);
}

function exists(rel) {
  return fs.existsSync(path.join(root, rel));
}

function read(rel) {
  return fs.readFileSync(path.join(root, rel), "utf8");
}

function allFiles(dir, predicate, out = []) {
  if (!fs.existsSync(path.join(root, dir))) return out;
  for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const rel = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) allFiles(rel, predicate, out);
    else if (entry.isFile() && predicate(rel)) out.push(rel);
  }
  return out;
}

const audit = readJsonFromAuditImports();
const live = new Set(audit.live || []);
const dead = new Set(audit.dead || []);
const src = new Set(audit.staged || []);

const jsFiles = [
  ...allFiles("public", (f) => f.endsWith(".js")),
  ...allFiles("src", (f) => f.endsWith(".js")),
].sort();

const outputKeywords = [
  "frameBus", "FrameBus", "led-framebus-publish", "ArtNet", "artnet", "DDP", "ddp",
  "serial", "Serial", "WebSocket", "ws://", "fetch(", "/api/artnet", "/api/live-frame"
];
const hotKeywords = ["requestAnimationFrame", "setInterval", "setTimeout", "localStorage", "dispatchEvent", "addEventListener", "commitState", "broadcastStateSync", "saveLocalState"];

function classify(rel) {
  if (live.has(rel)) return "LIVE_IMPORT";
  if (dead.has(rel)) return "UNREACHED_PUBLIC";
  if (src.has(rel)) return "SERVER_OR_STAGED_SRC";
  return "UNKNOWN";
}

function hits(rel, words) {
  let txt = "";
  try { txt = read(rel); } catch { return []; }
  return words.filter((w) => txt.includes(w));
}

const outputTouched = jsFiles
  .map((rel) => ({ rel, status: classify(rel), outputHits: hits(rel, outputKeywords), hotHits: hits(rel, hotKeywords) }))
  .filter((row) => row.outputHits.length || row.hotHits.length)
  .sort((a, b) => a.status.localeCompare(b.status) || a.rel.localeCompare(b.rel));

const primaryRuntime = [
  "public/runtime/frame_bus.js",
  "public/runtime/artnet_master_framebus_mirror_22ej.js",
  "public/runtime/live_serial_app_mirror_22cr.js",
  "public/runtime/quick_step_automator.js",
  "public/runtime/render_pipeline.js",
  "public/runtime/ui_state_sync.js",
  "public/runtime/output_lock_37ap.js",
  "public/app.js",
  "src/server/ws_controller.js",
  "src/output/artnet_sync_live_sender_22dq.js",
  "src/output/artnet_master_frame_store_22ej.js",
  "server.js"
].filter(exists);

const reportLines = [];
reportLines.push("# STEP37BA Active Runtime Map");
reportLines.push("");
reportLines.push("Generated by `npm run audit:active-runtime`.");
reportLines.push("");
reportLines.push("## Summary");
reportLines.push("");
reportLines.push(`- HTML roots found: ${audit.existingRoots.length}`);
reportLines.push(`- Live imported public JS files: ${audit.liveCount}`);
reportLines.push(`- Public JS files not reached from HTML/import graph: ${audit.deadCount}`);
reportLines.push(`- Server/staged src JS files: ${audit.stagedCount}`);
reportLines.push("");
reportLines.push("## Runtime roots");
reportLines.push("");
for (const rootHtml of audit.existingRoots) reportLines.push(`- ${rootHtml}`);
reportLines.push("");
reportLines.push("## Primary files that must be treated as ACTIVE");
reportLines.push("");
for (const rel of primaryRuntime) reportLines.push(`- ${rel} — ${classify(rel)}`);
reportLines.push("");
reportLines.push("## Output / hot-path candidates");
reportLines.push("");
reportLines.push("These files contain output, framebus, websocket, serial, ArtNet, timer, storage, event, or commit keywords. This is not a delete list; it is a review list.");
reportLines.push("");
reportLines.push("| Status | File | Output markers | Hot markers |");
reportLines.push("|---|---|---|---|");
for (const row of outputTouched) {
  const outs = row.outputHits.slice(0, 8).join(", ").replaceAll("|", "\\|") || "-";
  const hot = row.hotHits.slice(0, 8).join(", ").replaceAll("|", "\\|") || "-";
  reportLines.push(`| ${row.status} | \`${row.rel}\` | ${outs} | ${hot} |`);
}
reportLines.push("");
reportLines.push("## Safe cleanup rule from this step");
reportLines.push("");
reportLines.push("Do not delete anything solely because it is not imported statically. Some runtime files are loaded dynamically, through HTML, old debug pages, localStorage flags, or server routes. The safe next move is to add explicit ownership metadata first, then disable only one legacy writer at a time behind a flag.");
reportLines.push("");
reportLines.push("## Next recommended patch");
reportLines.push("");
reportLines.push("STEP37BB should add an Output Route Registry: one small runtime module listing allowed physical writers and their owner priority. That will let ArtNet, Serial, DDP, preview and debug producers be shown clearly in the UI before any legacy code is removed.");

const reportPath = path.join(outDir, "ACTIVE_RUNTIME_MAP_STEP37BA.md");
fs.writeFileSync(reportPath, reportLines.join("\n"));

const jsonPath = path.join(outDir, "active-runtime-map-step37ba.json");
fs.writeFileSync(jsonPath, JSON.stringify({
  generatedAt: new Date().toISOString(),
  summary: {
    htmlRoots: audit.existingRoots.length,
    livePublicJs: audit.liveCount,
    unreachedPublicJs: audit.deadCount,
    stagedSrcJs: audit.stagedCount
  },
  roots: audit.existingRoots,
  primaryRuntime,
  outputTouched
}, null, 2));

console.log(`Wrote ${path.relative(root, reportPath)}`);
console.log(`Wrote ${path.relative(root, jsonPath)}`);
